<#
.SYNOPSIS
    Regenerates Docs/Coverage.md from M365GapAssessment/Data/ControlMapping.json.
.DESCRIPTION
    The per-console finding tables, the finding count, severity split and CIS count come from the mapping file, so they cannot
    drift. The explanatory sections (how to run, not-covered roadmap, licence notes) are the text below: edit them here.
    Tests/CoverageDoc.Tests.ps1 fails when the committed Coverage.md differs from what this script produces.
.PARAMETER OutputPath
    Where to write the document. Defaults to Coverage.md next to this script.
.PARAMETER Date
    Date shown in the header (yyyy-MM-dd). Defaults to today. Tests pin it for a stable comparison.
.EXAMPLE
    pwsh ./Docs/Update-Coverage.ps1
#>
[CmdletBinding()]
param(
    [string]$OutputPath = (Join-Path $PSScriptRoot 'Coverage.md'),
    [string]$Date = (Get-Date -Format 'yyyy-MM-dd'),
    [string]$MappingPath = (Join-Path $PSScriptRoot '../M365GapAssessment/Data/ControlMapping.json')
)

$controls = @((Get-Content -Raw -Path $MappingPath | ConvertFrom-Json).controls)

# Which administration console owns each finding. First matching rule wins; anything else is the Entra admin center.
function Get-Console {
    param([string]$Id)
    switch -Regex ($Id) {
        '^ENT-(AUTH-007|GRP-003)$|^LIC-001$' { return 'Microsoft 365 admin center' }
        '^DFO-(009|010|012)$' { return 'Exchange admin center' }
        '^(DEF-ALR|DEF-INC|SSC-|EXO-006|EXO-007|EML-003|DFO-)' { return 'Microsoft Defender portal' }
        '^PUR-' { return 'Microsoft Purview portal' }
        '^EXO-' { return 'Exchange admin center' }
        '^EML-00[12]$' { return 'DNS (public records)' }
        '^TMS-' { return 'Teams admin center' }
        '^SPO-' { return 'SharePoint admin center' }
        '^DEF-DEV' { return 'Intune admin center' }
        default { return 'Microsoft Entra admin center' }
    }
}

$consoleOrder = 'Microsoft Entra admin center', 'Microsoft Defender portal', 'Microsoft Purview portal', 'Exchange admin center', 'Teams admin center',
    'SharePoint admin center', 'Intune admin center', 'Microsoft 365 admin center', 'DNS (public records)'

$bySeverity = $controls | Group-Object severity -AsHashTable -AsString
$sev = 'Critical', 'High', 'Medium', 'Low' | ForEach-Object { '{0} {1}' -f @($bySeverity[$_]).Count, $_ }
$cisCount = @($controls | Where-Object { $_.cis }).Count

$head = @'
# M365GapAssessment coverage

What the assessor checks, organised by the Microsoft 365 administration console where each setting lives, and what it does **not** check yet.

> Generated from `M365GapAssessment/Data/ControlMapping.json` on {DATE}: **{TOTAL} findings** ({SEV}); **{CIS}** carry a CIS Microsoft 365 reference.
> The tables below are generated by `Docs/Update-Coverage.ps1`; the explanatory text lives in that script. Do not edit this file by hand.

Every check ends as **Gap**, **Pass**, **NotAssessed** (Graph refused, a licence is missing, or there was nothing to evaluate) or **Accepted** (covered by an accepted-risk entry). NotAssessed counts as a failure in the score so unverifiable controls stay visible.
All checks are read-only (Graph `GET`, or `Get-*` cmdlets for Exchange, Teams and SharePoint).

## 1. How to run each area

| `-Domain` value | Default | Needs | Findings |
|---|:-:|---|---|
| `Licensing` | yes | Graph | LIC-001 (also drives licence-aware NotAssessed messages) |
| `EntraID` | yes | Graph | Conditional Access baseline, roles and PIM, MFA registration, stale accounts, app credentials and permissions, guests in privileged groups |
| `EntraPolicy` | yes | Graph | Consent and user settings, authentication methods, CA depth, PIM settings, cross-tenant access, guests, directory sync, risky users, governance, plus the baseline checks (Security Defaults, SSPR, lockout, password expiry, public groups, emergency access) |
| `Defender` | yes | Graph (beta for Intune) | Alerts, incidents, device compliance and encryption |
| `SecureScore` | yes | Graph | Score versus target, unimplemented controls |
| `EmailDns` | yes | Public DNS (DNS-over-HTTPS on macOS/Linux) | SPF, DMARC, DKIM for verified custom domains |
| `SharePoint` | yes | Graph (`SharePointTenantSettings.Read.All`) | Tenant sharing and sync settings |
| `ExchangeOnline` | **opt-in** | `ExchangeOnlineManagement` module | Forwarding, mailbox audit, modern auth, SMTP AUTH, shared mailboxes, anti-phishing, Safe Links |
| `DefenderO365` | **opt-in** | `ExchangeOnlineManagement` module (shares the Exchange sign-in) | Safe Attachments, Safe Links settings, anti-malware, anti-spam, preset policies, mail flow rules that bypass filtering, connection filter, external sender tag, Teams ZAP, user reporting |
| `Purview` | **opt-in** | `ExchangeOnlineManagement` module (`Connect-IPPSSession`, its own sign-in) | Unified audit log, DLP, sensitivity labels, retention, insider risk |
| `Teams` | **opt-in** | `MicrosoftTeams` module | Teams tenant policies |

## 2. Coverage by administration console
'@

$tail = @'

## 3. What is not covered yet

No findings exist for these areas. They are the roadmap, roughly in priority order.

| Area | Not yet checked | Why it is harder |
|---|---|---|
| **Microsoft Purview (depth)** | Auto-labeling and mandatory-labeling settings, sensitive information types, communication compliance, eDiscovery and audit retention policies, data security posture | Compliance PowerShell objects with licence-dependent availability |
| **Defender for Office 365 (depth)** | Quarantine policies, impersonation and mailbox-intelligence settings, tenant allow/block list review, attack simulation training | Exchange Online PowerShell; several settings are portal-only |
| **Exchange (depth)** | Connectors, OWA policies, mailbox permissions and delegation, calendar sharing, mailbox audit bypass | Exchange Online PowerShell |
| **Intune (depth)** | Enrollment restrictions, app protection (MAM), update rings, configuration baselines | Graph beta; the tenant may have no managed devices, so results are often NotAssessed |
| **Entra (depth)** | Device join and registration settings, session controls and token protection, authentication contexts, workload identities, cross-tenant sync, PIM for groups, entitlement management | Some settings have no stable Graph surface |
| **Microsoft 365 admin center (org settings)** | Idle session timeout, Forms, Sway, Bookings, Copilot and AI settings, Office on the web | Several settings are exposed only in the portal |
| **Teams (depth)** | App permission and setup policies, Teams Phone | MicrosoftTeams PowerShell |
| **SharePoint (depth)** | Ownerless sites, site-level sharing overrides, site sensitivity labels, versioning and retention | Needs per-site enumeration |
| **Power Platform admin center** | DLP policies, environments, tenant isolation | Separate admin API |
| **Defender for Endpoint, Identity and Cloud Apps** | Product-specific configuration (the generic alerts and incidents are covered) | Separate APIs and licences |
| **Azure subscriptions** | Defender for Cloud plans, storage and Key Vault exposure, network security groups | Needs Azure Resource Manager access; not part of the Microsoft 365 Graph surface |

## 4. Where coverage is deepest and thinnest

- **Deepest:** Entra ID, Teams and SharePoint sharing: Graph and the Teams/SharePoint admin APIs expose these settings directly.
- **Thinnest:** Intune (2 checks) and Purview beyond the basics (audit, DLP, labels, retention). Exchange, Defender for Office 365 and Purview data come from Exchange Online and compliance PowerShell, so they are opt-in domains that need the `ExchangeOnlineManagement` module and a separate sign-in.
- **Secure Score is a safety net.** Its recommended actions (the SSC findings) already surface many of the uncovered areas above (DLP, anti-spam, mail flow), but as one grouped finding without per-setting detail.

## 5. Licence and permission notes

- Checks that need a licence carry a `license` tag in the mapping (Entra ID P1/P2, Intune). When Graph refuses the call, the finding is NotAssessed and the detail says which licence is missing.
- Security Defaults is taken into account by `ENT-CA-003` and `ENT-CA-004` (it blocks legacy authentication and requires admin MFA), and lowers the severity of `ENT-CA-006`. Device-code sign-in does not work in tenants with Security Defaults enabled.
- `ENT-CA-009` (emergency access accounts) only **nominates** candidates from Conditional Access exclusions; a person must confirm they really are break-glass accounts.
- First sign-in in a tenant needs one-time admin consent for the read-only Graph scopes (see the README).
- **Sovereign clouds:** `-Environment Global|USGov|USGovDoD|China` sends Graph, Exchange, Purview and Teams to the same cloud. Only `Global` has been run against a live tenant; the others are wired but untested, the tool warns when you select one, and Teams is not supported in `China`. An endpoint a cloud does not offer shows as NotAssessed.
- **Global Administrator guard:** Global Reader is enough, so a delegated sign-in as an account that holds Global Administrator asks for confirmation (default No) and, in a session that cannot ask (non-interactive, redirected input, scheduled job), stops before anything is assessed unless `-AllowGlobalAdministrator` is passed. `-SkipRoleCheck` does not skip it; app-only sessions are not checked.
- **Global Reader:** the checks return the same results as Global Administrator across Graph, Exchange, Defender for Office 365, Purview and Teams, except `PUR-006` (insider risk) and `DFO-014` (user reporting), which report NotAssessed for a read-only role. The reports list which account each service signed in as.
- **Optional report additions:** `-IncludeEvidence` writes the full affected-item list for each gap to `evidence/`, and `-CisView` regroups findings by CIS recommendation number.
'@

$out = [System.Text.StringBuilder]::new()
[void]$out.AppendLine(($head.Replace('{DATE}', $Date).Replace('{TOTAL}', "$($controls.Count)").Replace('{SEV}', ($sev -join ', ')).Replace('{CIS}', "$cisCount")))

foreach ($console in $consoleOrder) {
    $rows = [System.Collections.Generic.List[object]]::new()
    foreach ($c in $controls) { if ((Get-Console $c.id) -eq $console) { $rows.Add($c) } }
    $rows.Sort([Comparison[object]] { param($a, $b) [string]::CompareOrdinal($a.id, $b.id) })

    [void]$out.AppendLine()
    [void]$out.AppendLine("### $console ($($rows.Count))")
    [void]$out.AppendLine()
    [void]$out.AppendLine('| ID | Severity | CIS | Check |')
    [void]$out.AppendLine('|---|---|---|---|')
    foreach ($c in $rows) {
        $cis = if ($c.cis) { @($c.cis) -join ', ' } else { [string][char]0x2013 }
        [void]$out.AppendLine("| $($c.id) | $($c.severity) | $cis | $($c.name) |")
    }
}
[void]$out.Append($tail)

# LF line endings and a trailing newline keep the committed file stable across platforms.
[System.IO.File]::WriteAllText($OutputPath, (($out.ToString() -replace "`r`n", "`n").TrimEnd("`n") + "`n"), [System.Text.UTF8Encoding]::new($false))
Write-Verbose "Wrote $OutputPath ($($controls.Count) findings)"
